import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),dist=path.join(root,'dist');
const read=name=>readFile(path.join(dist,name),'utf8');
const [html,css,terrain,island]=await Promise.all(['index.html','style.css','terrain.js','island.js'].map(read));
const cssBlock=/<script>\s*window\.nagiBoot=[\s\S]*?<\/script>/;
const loaderBlock=/<script type="module">[\s\S]*?<\/script>/;
if(!cssBlock.test(html)||!loaderBlock.test(html))throw new Error('Missing expected game bootstrap');
const inline=terrain.replace(/export /g,'')+'\n'+island.slice(island.indexOf('\n')+1);
const standalone=html.replace(cssBlock,'<style>\n'+css+'\n</style>').replace(loaderBlock,'<script type="module">\n'+inline+'\n</script>');
await writeFile(path.join(dist,'nagi-standalone.html'),standalone);
await mkdir(path.join(dist,'assets'),{recursive:true});
await copyFile(path.join(root,'assets/nagi-icon-120.png'),path.join(dist,'assets/nagi-icon-120.png'));
const manifest=JSON.parse(await readFile(path.join(root,'manifest.webmanifest'),'utf8'));
manifest.start_url='./index.html';manifest.scope='./';
await writeFile(path.join(dist,'manifest.webmanifest'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(path.join(root,'.nojekyll'),'');
console.log('Built standalone game, app manifest and existing icon. GitHub Pages entry remains index.html → dist/index.html.');
